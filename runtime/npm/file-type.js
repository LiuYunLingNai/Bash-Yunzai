export const fileTypeFromBuffer = async buf => {
  const b = buf instanceof Uint8Array ? buf : new Uint8Array(buf)
  for (const [ext, mime, sig] of SIG) if (sig.every((v, i) => v === undefined || b[i] === v)) return { ext, mime }
  return undefined
}
export const fileTypeFromStream = async () => undefined
export const fileTypeFromFile = async f => fileTypeFromBuffer((await import("node:fs")).default.readFileSync(f))
export const supportedExtensions = new Set(SIG.map(i => i[0]))
export const supportedMimeTypes = new Set(SIG.map(i => i[1]))
